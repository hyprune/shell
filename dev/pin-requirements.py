#!/usr/bin/env python3
"""Write requirements.txt: the bridge's runtime dependencies at exact versions with
SHA-256 hashes from PyPI (Linux wheels and the sdist), for `pip --require-hashes`.

  python3 dev/pin-requirements.py      # edit PINS first to bump a version
"""
import json
from pathlib import Path
import urllib.request

# jsonschema and its whole dependency closure, for Python 3.11+.
PINS = [('jsonschema', '4.26.0', ''), ('attrs', '26.1.0', ''), ('jsonschema-specifications', '2025.9.1', ''),
        ('referencing', '0.37.0', ''), ('rpds-py', '2026.9.1', ''),
        ('typing-extensions', '4.16.0', ' ; python_version < "3.13"')]


def hashes(name, version):
    with urllib.request.urlopen(f'https://pypi.org/pypi/{name}/{version}/json') as response:
        files = json.load(response)['urls']
    keep = [f for f in files if f['packagetype'] == 'sdist' or 'none-any' in f['filename'] or 'linux' in f['filename']]
    return sorted(f['digests']['sha256'] for f in keep)


lines = ['# Generated by dev/pin-requirements.py: exact versions and hashes for pip --require-hashes.',
         '# The bridge needs only jsonschema; the rest is its dependency closure.']
for name, version, marker in PINS:
    lines.append(f'{name}=={version}{marker} \\')
    lines += [f'    --hash=sha256:{h} \\' for h in hashes(name, version)]
    lines[-1] = lines[-1].removesuffix(' \\')
Path(__file__).resolve().parents[1].joinpath('requirements.txt').write_text('\n'.join(lines) + '\n')
